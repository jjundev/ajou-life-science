SKILL = Path(__file__).resolve().parents[1]
SIBLINGS = SKILL.parent
KINDS = ('정리노트', '복습문제', '문제설명')
REVIEWS = ('source_visual', 'content', 'independent', 'browser')
INPUT_RE = re.compile(r'(\d{4}) 공부(?: ([1-9]\d*))?\.md')


def nfc(value):
    return unicodedata.normalize('NFC', str(value))


def read(path):
    return json.loads(Path(path).read_text(encoding='utf-8'))


def write(path, value):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')


def existing(path):
    """Resolve NFC/NFD path components without guessing between duplicate names."""
    path = Path(path).absolute()
    if path.exists():
        return path.resolve()
    parent = existing(path.parent)
    hits = [p for p in parent.iterdir() if nfc(p.name) == nfc(path.name)]
    if len(hits) != 1:
        raise ValueError(f'경로 없음 또는 여러 후보: {path}')
    return hits[0].resolve()


def inside(repo, path):
    path = existing(path if Path(path).is_absolute() else repo / path)
    if not path.is_relative_to(repo):
        raise ValueError(f'저장소 밖 경로: {path}')
    return path


def fingerprint(repo, path):
    path = inside(repo, path)
    return {'path': nfc(path.relative_to(repo).as_posix()),
            'sha256': hashlib.sha256(path.read_bytes()).hexdigest()}


def valid_date(value):
    try:
        datetime.strptime('2000' + value, '%Y%m%d')
    except ValueError:
        raise ValueError(f'잘못된 날짜: {value}') from None


def discover(repo):
    groups = {}
    for path in sorted(existing(repo / 'SSTT').iterdir(), key=lambda p: nfc(p.name)):
        match = INPUT_RE.fullmatch(nfc(path.name))
        if path.is_file() and match:
            date, number = match.groups()
            valid_date(date)
            groups.setdefault(date, []).append((int(number or 1), path))
    result = {}
    for date, items in sorted(groups.items()):
        if len({x[0] for x in items}) != len(items):
            raise ValueError(f'같은 날짜·번호의 입력 여러 후보: {date}')
        result[date] = [fingerprint(repo, p) for _, p in sorted(items)]
    return result


def stored_inputs(repo, entries):
    result = {}
    for entry in entries:
        parts = nfc(entry['path']).replace('\\', '/').split('/')
        # Legacy 0908 recorded absolute paths; rebase only the SSTT suffix.
        if 'SSTT' in parts:
            index = len(parts) - 1 - parts[::-1].index('SSTT')
            if len(parts[index:]) == 2:
                result['/'.join(parts[index:])] = entry['sha256']
    return result


def artifacts_complete(out):
    for kind in KINDS:
        files = list(out.glob(kind + '_*.html'))
        if len(files) != 1 or not (out / '.assets' / (files[0].stem + '.md')).is_file():
            return False
    reports = list((out / '.assets').glob('자료_문제설명_*/validation.json'))
    return len(reports) == 1 and all(read(reports[0]).get(k, {}).get('status') == 'pass' for k in REVIEWS)


def records(repo):
    result = []
    root = repo / '약점노트'
    if not root.exists():
        return result
    candidates = {p.parent.parent for p in root.rglob('.pack/source-manifest.json')}
    for day in root.iterdir():
        if day.is_dir() and re.fullmatch(r'\d{4}', day.name):
            for out in [day, *[p for p in day.iterdir() if p.is_dir() and re.fullmatch(r'v[1-9]\d*', p.name)]]:
                if (out/'.pack').exists() or any(out.glob('*.html')):
                    candidates.add(out)
    for out in sorted(candidates):
        path = out/'.pack/source-manifest.json'
        try:
            data = read(path)
            inputs = stored_inputs(repo, data if isinstance(data, list) else data['inputs'])
            meta_path = path.parent / 'weakness-run.json'
            meta = read(meta_path) if meta_path.exists() else None
            complete = artifacts_complete(out) and (not meta_path.exists() or
                        isinstance(meta, dict) and meta.get('status') == 'complete')
            if meta and complete:
                required = {p.relative_to(out).as_posix() for p in out.glob('*.html')}
                required |= {f'.assets/{Path(name).stem}.md' for name in list(required)}
                complete = required.issubset(meta.get('artifact_hashes', {})) and all((out / name).resolve().is_relative_to(out.resolve()) and (out / name).is_file() and hashlib.sha256((out/name).read_bytes()).hexdigest() == digest
                               for name, digest in meta.get('artifact_hashes', {}).items())
            if inputs:
                result.append((inputs, complete))
            else:
                result.append(({f'@date/{out.relative_to(root).parts[0]}': ''}, False))
        except (OSError, ValueError, KeyError, TypeError):
            # An unreadable ledger is not evidence of completion.
            result.append(({f'@date/{out.relative_to(root).parts[0]}': ''}, False))
    return result


def output_plan(repo, date, inputs, status):
    root = repo / '약점노트' / date
    version = 1
    if root.exists() and any(root.iterdir()):
        version = 2
        while (root / f'v{version}').exists():
            version += 1
    out = root if version == 1 else root / f'v{version}'
    slug = f'Weakness_{date}_v{version}'
    return dict(date=date, inputs=inputs, status=status, version=version, slug=slug,
                output=out.relative_to(repo).as_posix())


def select(repo, target=None, regenerate=False):
    repo = existing(repo)
    groups = discover(repo)
    previous = records(repo)
    catalog = []
    for date, inputs in groups.items():
        current = {x['path']: x['sha256'] for x in inputs}
        related = [(old, done) for old, done in previous if set(old) & set(current) or f'@date/{date}' in old]
        status = 'pending'
        if any(done and old == current for old, done in related):
            status = 'complete'
        elif any(done for _, done in related):
            status = 'changed'
        elif related:
            status = 'incomplete'
        catalog.append(output_plan(repo, date, inputs, status))
    if target is None or target == 'remaining':
        if regenerate:
            raise ValueError('--regenerate는 날짜 또는 파일을 명시하세요')
        selected = [x for x in catalog if x['status'] == 'pending']
        if target is None:
            selected = selected[:1]
    elif re.fullmatch(r'\d{4}', target):
        valid_date(target)
        selected = [x for x in catalog if x['date'] == target]
        if not selected:
            raise ValueError(f'SSTT 날짜 없음: {target}')
        selected = [x for x in selected if regenerate or x['status'] == 'pending']
    else:
        path = inside(repo, Path(target))
        if path.parent != existing(repo / 'SSTT') or not INPUT_RE.fullmatch(nfc(path.name)):
            raise ValueError('SSTT의 MMDD 공부[ 번호].md 파일만 지정하세요')
        date = INPUT_RE.fullmatch(nfc(path.name))[1]
        valid_date(date)
        inputs = [fingerprint(repo, path)]
        key, digest = inputs[0]['path'], inputs[0]['sha256']
        related = [(old, done) for old, done in previous if key in old or f'@date/{date}' in old]
        status = ('complete' if any(done and old.get(key) == digest for old, done in related)
                  else 'changed' if any(done for _, done in related) else 'incomplete' if related else 'pending')
        selected = [output_plan(repo, date, inputs, status)] if regenerate or status == 'pending' else []
    return dict(selected=selected, catalog=catalog)


def prepare(repo, target, run, regenerate=False):
    if target == 'remaining':
        raise ValueError('select remaining 후 날짜마다 prepare를 호출하세요')
    repo = existing(repo)
    selected = select(repo, target, regenerate)['selected']
    if len(selected) != 1:
        raise ValueError('처리할 새 입력 없음; 변경·미완료·완료 입력은 명시 --regenerate')
    run = Path(run).resolve()
    if run.exists():
        raise ValueError('새 RUN 경로가 필요해요')
    if run.is_relative_to(repo):
        raise ValueError('RUN은 저장소 밖의 임시 경로를 쓰세요')
    run.mkdir(parents=True)
    plan = dict(selected[0], repo=str(repo), run=str(run), run_id=uuid.uuid4().hex,
                grouped=target is None or bool(re.fullmatch(r'\d{4}', target)))
    for name in ('sections', 'cards', 'figures', 'work'):
        (run/name).mkdir()
    write(run/'plan.json', plan)
    return plan


def load_plan(run):
    run = existing(run)
    plan = read(run/'plan.json')
    repo = existing(plan['repo'])
    for entry in plan['inputs']:
        if fingerprint(repo, entry['path']) != entry:
            raise ValueError(f'입력 변경: 새 RUN에서 prepare부터 다시 실행: {entry["path"]}')
    if plan.get('grouped') and discover(repo).get(plan['date']) != plan['inputs']:
        raise ValueError('입력 변경: 같은 날짜의 파일 구성이 달라졌어요')
    return plan


def adapt_export(source, pack_relative, document_id):
    """Adapt only generated JS, keeping sibling templates unchanged."""
    marker = "    if (root.name === '복습노트') {"
    if source.count(marker) != 1:
        raise ValueError('저장 경로 어댑터와 기존 생성기 버전이 달라요')
    parts = pack_relative.split('/')
    if any(not re.fullmatch(r'\d{4}|v[2-9]\d*|v1\d+', p) for p in parts):
        raise ValueError('잘못된 팩 상대 경로')
    custom = '''    if (root.name === '약점노트') {
      let pack = root;
      for (const part of %s) {
        pack = await child(pack, part, false);
        if (!pack) return null;
      }
      try { await pack.getFileHandle(%s); }
      catch (error) { if (error && error.name === 'NotFoundError') return null; throw error; }
      return inAssets(pack);
    }
''' % (json.dumps(parts, ensure_ascii=False), json.dumps(document_id, ensure_ascii=False))
    source = source.replace(marker, custom + marker)
    source = source.replace('복습노트/날짜 폴더(또는 복습노트 폴더)', '약점노트의 이 HTML이 있는 폴더(또는 약점노트 폴더)')
    source = source.replace("'복습노트/' +", "'약점노트/' +")
    return source


class StudyHTML(HTMLParser):
    """Inventory pedagogic units, including collapsed material; never mark them read."""
    VOID = {'area', 'base', 'br', 'col', 'embed', 'hr', 'img', 'input', 'link', 'meta', 'param', 'source', 'track', 'wbr'}

    def __init__(self, role):
        super().__init__(convert_charrefs=True)
        self.role, self.stack = role, []
        self.items, self.choices, self.sections = [], {}, {}

    def unit(self):
        return next((attrs['_unit'] for _, attrs in reversed(self.stack) if '_unit' in attrs), None)

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        cls = attrs.get('class', '').split()
        expected = 'card' if self.role == 'review' else 'topic'
        if tag == 'article' and expected in cls:
            key = attrs.get('id')
            if not key or key in self.items:
                raise ValueError('학습 항목 ID 누락 또는 중복')
            self.items.append(key)
            attrs['_unit'] = key
        unit = attrs.get('_unit') or self.unit()
        if unit and attrs.get('data-explanation'):
            self.sections.setdefault(unit, []).append(attrs['data-explanation'])
        if unit and tag == 'li' and any('choices' in a.get('class', '').split() for _, a in self.stack):
            attrs['_choice'] = attrs.get('data-choice')
            attrs['_text'] = []
            attrs['_choice_unit'] = unit
        if tag not in self.VOID:
            self.stack.append((tag, attrs))

    def handle_data(self, text):
        for _, attrs in self.stack:
            if '_text' in attrs:
                attrs['_text'].append(text)

    def handle_endtag(self, tag):
        index = next((i for i in range(len(self.stack)-1, -1, -1) if self.stack[i][0] == tag), None)
        if index is None:
            return
        for _, attrs in self.stack[index:]:
            if '_choice_unit' in attrs:
                match = re.match(r'\s*(?:\((\d+)\)|([A-Z])[.)])', ''.join(attrs['_text']))
                key = attrs['_choice'] or (next(x for x in match.groups() if x) if match else None)
                if key:
                    self.choices.setdefault(attrs['_choice_unit'], []).append(key)
        del self.stack[index:]

    def handle_startendtag(self, tag, attrs):
        self.handle_starttag(tag, attrs)
        if tag not in self.VOID:
            self.handle_endtag(tag)


def study_inventory(repo, folder, overrides=None):
    repo = existing(repo)
    folder = inside(repo, folder)
    if not folder.is_dir() or not folder.is_relative_to(existing(repo/'복습노트')) or folder == existing(repo/'복습노트'):
        raise ValueError('복습노트의 해당 차시 폴더를 지정하세요')
    overrides = overrides or {}
    files, missing, suites = {}, [], set()
    for role, kind in zip(('note', 'review', 'explanation'), KINDS):
        candidates = sorted(p for p in folder.iterdir() if p.is_file() and nfc(p.name).startswith(kind+'_') and p.suffix == '.html')
        if role in overrides:
            selected = inside(repo, overrides[role])
            if selected.parent != folder or selected not in candidates:
                raise ValueError('해당 차시·종류와 다른 HTML 지정')
            candidates = [selected]
        if len(candidates) > 1:
            raise ValueError(f'{role} 여러 후보: 파일을 명시하세요: ' + ', '.join(str(p) for p in candidates))
        if not candidates:
            missing.append(role)
            continue
        path = candidates[0]
        parsed = StudyHTML(role)
        parsed.feed(path.read_text(encoding='utf-8'))
        if not parsed.items:
            raise ValueError(f'학습 항목 없음: {path}')
        suites.add(nfc(path.stem)[len(kind)+1:])
        files[role] = dict(fingerprint(repo, path), items=parsed.items,
                           choices=parsed.choices, sections=parsed.sections)
    review = files.get('review', {}).get('items', [])
    explanation = files.get('explanation', {}).get('items', [])
    return dict(folder=nfc(folder.relative_to(repo).as_posix()), files=files, missing=missing,
                review_only=[p for p in review if p not in explanation],
                explanation_only=[p for p in explanation if p not in review], suite_mismatch=len(suites)>1)


def check_transcript_evidence(repo, inputs, entries):
    if not entries:
        raise ValueError('발언 근거 필요')
    for ev in entries:
        if ev['path'] not in inputs:
            raise ValueError('선택하지 않은 SSTT를 근거로 사용')
        lines = inside(repo, ev['path']).read_text(encoding='utf-8').splitlines()
        if not 1 <= ev['line_start'] <= ev['line_end'] <= len(lines) or not ev.get('quote') or ev['quote'] not in '\n'.join(lines[ev['line_start']-1:ev['line_end']]):
            raise ValueError('원문 인용·줄 범위 불일치')


def validate_study_sources(plan, run, data, manifest):
    repo = existing(plan['repo'])
    inputs = {x['path'] for x in plan['inputs']}
    if data.get('schema') != 2 or not data.get('study_packs'):
        raise ValueError('schema 2의 차시 HTML 3종·전체 읽기 기록 필요')
    packs, assigned = {}, set()
    for pack in data['study_packs']:
        name = pack['folder']
        if name in packs or not pack.get('match_evidence') or not pack.get('input_paths') or not set(pack['input_paths']).issubset(inputs):
            raise ValueError('차시 연결 근거·선택한 SSTT 경로 필요')
        current = study_inventory(repo, name, {role: entry['path'] for role, entry in pack['files'].items()})
        if any(pack.get(key) != current[key] for key in current):
            raise ValueError('차시 자료 변경·누락 또는 학습 항목 목록 불일치')
        if not current['files']:
            raise ValueError('해당 차시 학습 자료 없음')
        reading = pack.get('reading', {})
        for role, entry in current['files'].items():
            row = reading.get(role, {})
            if row.get('items') != entry['items'] or not row.get('evidence'):
                raise ValueError(f'{role}: 전체 읽기 범위·검토 근거 필요')
            path = existing(run/row['evidence'])
            if not path.is_relative_to(run) or not path.is_file() or not path.read_bytes().strip():
                raise ValueError('전체 읽기 근거는 RUN 안의 비어 있지 않은 파일이어야 해요')
        packs[name] = current
        assigned.update(pack['input_paths'])
    # Unresolved sessions can be excluded rather than silently mapped to a different lesson.
    for entry in data.get('unresolved_sessions', []):
        if entry.get('path') not in inputs or not entry.get('reason'):
            raise ValueError('미확정 차시의 입력 경로·보류 이유 필요')
        assigned.add(entry['path'])
    if assigned != inputs:
        raise ValueError('모든 선택 SSTT의 차시 연결 또는 보류 기록 필요')
    for w in data.get('weaknesses', []):
        context = w.get('source_context', {})
        if context.get('pack') not in packs:
            raise ValueError('발언의 원래 차시 연결 필요')
        pack = packs[context['pack']]
        source_inputs = next(p['input_paths'] for p in data['study_packs'] if p['folder'] == context['pack'])
        if any(ev['path'] not in source_inputs for ev in w.get('evidence', [])):
            raise ValueError('발언과 다른 차시 자료 연결')
        note = pack['files'].get('note', {})
        if not set(context.get('note_topics', [])).issubset(note.get('items', [])):
            raise ValueError('원래 정리노트 토픽 앵커 없음')
        mode = context.get('match')
        if mode == 'confirmed':
            if any(not isinstance(context.get(key), list) for key in ('choices', 'note_topics', 'explanation_sections')) or not context['explanation_sections'] or (note and not context['note_topics']):
                raise ValueError('확정 연결의 보기·토픽·해설 구역 목록과 관련 해설 구역이 필요해요')
            pid = context.get('problem')
            review = pack['files'].get('review', {})
            explanation = pack['files'].get('explanation', {})
            if pack['suite_mismatch'] or pid not in review.get('items', []) or pid not in explanation.get('items', []):
                raise ValueError('원래 문항·문제설명 대응 누락 또는 다른 파일 세트')
            if not set(context.get('choices', [])).issubset(review.get('choices', {}).get(pid, [])):
                raise ValueError('원래 문항 보기 ID 없음')
            if not set(context.get('explanation_sections', [])).issubset(explanation.get('sections', {}).get(pid, [])):
                raise ValueError('원래 문제설명 구역 없음')
        elif mode in ('candidate', 'concept'):
            if not context.get('reason') or context.get('problem') is not None:
                raise ValueError('미확정 문항은 확정 ID 대신 후보·개념 발언 이유 필요')
            candidates = context.get('candidates', [])
            if mode == 'candidate' and (not candidates or not set(candidates).issubset(pack['files'].get('review', {}).get('items', []))):
                raise ValueError('원래 문항 후보 ID 없음')
        else:
            raise ValueError('발언·원래 문항 연결 상태 필요')
        status = w.get('status')
        if status in ('self_corrected', 'study_corrected'):
            correction = w.get('correction', {})
            origin = correction.get('origin')
            if status == 'self_corrected' and origin != 'independent':
                raise ValueError('자기교정은 독립적인 추론 근거가 있을 때만 표시하세요')
            if status == 'study_corrected' and origin not in ('solution', 'unknown'):
                raise ValueError('공부 중 정정은 해설 참고·정정 경로 미확인을 구분하세요')
            check_transcript_evidence(repo, set(source_inputs), correction.get('evidence', []))


def check_diagnosis(plan, run, manifest):
    repo = existing(plan['repo'])
    data = read(run/'diagnosis.json')
    if data.get('inputs') != plan['inputs'] or not data.get('review_note_search'):
        raise ValueError('diagnosis: 입력 스냅샷·기존 복습노트 검색 기록 필요')
    references = data.get('references', [])
    if not any(r.get('role') in ('lecture', 'textbook') for r in references):
        raise ValueError('diagnosis: 강의자료 또는 교재의 검증 근거 필요')
    for ref in references:
        if fingerprint(repo, ref['path']) != {k: ref[k] for k in ('path', 'sha256')} or not ref.get('locations'):
            raise ValueError('참고 자료 변경 또는 근거 위치 누락')
    validate_study_sources(plan, run, data, manifest)
    topics = {t['id'] for s in manifest['sections'] for t in s['topics']}
    problems = {p['id']: p for p in manifest['problems']}
    covered, ids = set(), set()
    for w in data.get('weaknesses', []):
        if w['id'] in ids or w['status'] not in ('uncorrected', 'self_corrected', 'study_corrected', 'hesitant_application', 'name_recall'):
            raise ValueError('중복 약점 ID 또는 판정 보류 대상의 문제화')
        ids.add(w['id'])
        if w['topic'] not in topics or not w.get('criterion') or not w.get('later_check') or not w.get('evidence') or not w.get('problems'):
            raise ValueError('약점의 기준·이후 발언 확인·토픽·문항 연결 필요')
        check_transcript_evidence(repo, {x['path'] for x in plan['inputs']}, w['evidence'])
        for pid in w['problems']:
            if pid not in problems or problems[pid]['anchor'] != w['topic']:
                raise ValueError('약점·문항·정리노트 앵커 연결 불일치')
            covered.add(pid)
    if not ids or covered != set(problems):
        raise ValueError('약점 신호 없음 또는 근거 없는 문항')
    if any('prof' in t['layers'] for s in manifest['sections'] for t in s['topics']):
        raise ValueError('SSTT 발언을 교수님 말씀 레이어로 표시하지 마세요')
    return data


def archive_study_reading(data, run, out):
    archived = json.loads(json.dumps(data))
    for index, pack in enumerate(archived['study_packs'], 1):
        for role in pack['files']:
            row = pack['reading'][role]
            source = existing(run/row['evidence'])
            relative = f'.pack/study-reading/{index}-{role}{source.suffix}'
            destination = out/relative
            destination.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(source, destination)
            row['archived_evidence'] = relative
            row['evidence_sha256'] = hashlib.sha256(source.read_bytes()).hexdigest()
    return archived


def check_archived_diagnosis(data, run, out):
    archived = read(out/'.pack/diagnosis.json')
    for pack in archived.get('study_packs', []):
        for role in pack['files']:
            row = pack['reading'][role]
            relative = row.pop('archived_evidence', None)
            digest = row.pop('evidence_sha256', None)
            if not relative or not digest:
                raise ValueError('전체 읽기 근거 보존 누락: 다시 조립하세요')
            path = existing(out/relative)
            if not path.is_relative_to(out.resolve()) or hashlib.sha256(path.read_bytes()).hexdigest() != digest or hashlib.sha256(existing(run/row['evidence']).read_bytes()).hexdigest() != digest:
                raise ValueError('전체 읽기 근거 변경: 다시 조립·검토하세요')
    if archived != data:
        raise ValueError('진단 변경: 다시 조립·검토하세요')


def call(script, *args):
    subprocess.run([sys.executable, str(script), *map(str, args)], check=True)


def check_pair(plan, out, run):
    names = [f'{kind}_{plan["date"]}_{plan["slug"]}.html' for kind in KINDS]
    call(SIBLINGS/'bio-review-pack/scripts/check_html.py', '--manifest', run/'manifest.json', '--note', out/names[0], '--review', out/names[1])
    return names


def assemble(run):
    run = existing(run)
    plan = load_plan(run)
    manifest = read(run/'manifest.json')
    if (manifest['range'], manifest['slug']) != (plan['date'], plan['slug']):
        raise ValueError('manifest 날짜·slug는 plan과 같아야 해요')
    data = check_diagnosis(plan, run, manifest)
    call(SIBLINGS/'bio-review-pack/scripts/manifest.py', run/'manifest.json')
    repo = existing(plan['repo'])
    out = repo/plan['output']
    if not out.resolve().is_relative_to((repo/'약점노트').resolve()) or not out.resolve().is_relative_to(repo):
        raise ValueError('약점노트 밖 출력 경로')
    if out.exists() and any(out.iterdir()):
        meta = out/'.pack/weakness-run.json'
        if not meta.exists() or read(meta).get('run_id') != plan['run_id'] or read(meta).get('status') != 'draft':
            raise ValueError('기존 결과 보존: 새 RUN의 --regenerate를 쓰세요')
        if any((out/'.assets/풀이기록').glob('*')):
            raise ValueError('풀이기록이 있는 초안 보존: 새 버전 필요')
        backup = run/'work'/('previous-' + uuid.uuid4().hex)
        shutil.copytree(out, backup)
    write(out/'.pack/weakness-run.json', dict(plan, status='draft'))
    write(out/'.pack/source-manifest.json', plan['inputs'])
    call(SIBLINGS/'bio-review-pack/scripts/assemble.py', '--run', run, '--out', out)
    review = out/f'복습문제_{plan["date"]}_{plan["slug"]}.html'
    review.write_text(adapt_export(review.read_text(encoding='utf-8'), '/'.join(Path(plan['output']).parts[1:]), review.name), encoding='utf-8')
    names = check_pair(plan, out, run)
    call(SIBLINGS/'bio-review-pack/scripts/html2md.py', out/names[0], out/names[1], '--check')
    write(out/'.pack/diagnosis.json', archive_study_reading(data, run, out))
    (out/'.assets/풀이기록').mkdir(parents=True, exist_ok=True)
    return dict(output=str(out), note=str(out/names[0]), review=str(review),
                next='bio-problem-explain: extract --target <absolute review path above>; four reviews and publish, then finish')


def verify_explanation(repo, out, review_name):
    report_path = next((out/'.assets').glob('자료_문제설명_*/validation.json'))
    report = read(report_path)
    manifest = read(report_path.parent/'manifest.json')
    if manifest.get('source_sha256') != hashlib.sha256((out/review_name).read_bytes()).hexdigest():
        raise ValueError('문제설명 검토 후 입력 변경')
    if report.get('input_hash') != manifest.get('input_hash') or not report.get('artifact_hashes'):
        raise ValueError('문제설명 검토 해시 누락·불일치')
    for name, digest in report['artifact_hashes'].items():
        path = inside(repo, out/name)
        if not path.is_relative_to(out.resolve()) or hashlib.sha256(path.read_bytes()).hexdigest() != digest:
            raise ValueError('문제설명 검토 후 산출물 변경')
    for kind in REVIEWS:
        entry = report.get(kind, {})
        if entry.get('status') != 'pass' or not entry.get('reviewer') or not entry.get('evidence'):
            raise ValueError('문제설명 실제 검토 미완료')
    if not report.get('references'):
        raise ValueError('문제설명 검토 참고자료 누락')
    for ref in report['references']:
        if hashlib.sha256(inside(repo, ref['path']).read_bytes()).hexdigest() != ref['sha256']:
            raise ValueError('문제설명 검토 후 참고 자료 변경')
    return report


def review_evidence(run, item):
    if item.get('status') != 'pass' or not isinstance(item.get('reviewer'), str) or not item['reviewer'].strip() or not item.get('evidence'):
        raise ValueError('실제 진단·정리노트/복습문제 화면 검토 필요')
    path = existing(run/item['evidence'])
    if not path.is_relative_to(run) or not path.is_file():
        raise ValueError('팩 검토 근거는 RUN 안의 파일이어야 해요')
    if not path.read_bytes().strip():
        raise ValueError('팩 검토 근거 파일이 비어 있어요')
    return path


def finish(run):
    run = existing(run)
    plan = load_plan(run)
    repo = existing(plan['repo'])
    out = repo/plan['output']
    if not out.resolve().is_relative_to((repo/'약점노트').resolve()) or not out.resolve().is_relative_to(repo):
        raise ValueError('약점노트 밖 출력 경로')
    meta = read(out/'.pack/weakness-run.json')
    if meta.get('run_id') != plan['run_id'] or meta.get('status') != 'draft':
        raise ValueError('현재 RUN의 초안만 완료 처리할 수 있어요')
    data = check_diagnosis(plan, run, read(run/'manifest.json'))
    check_archived_diagnosis(data, run, out)
    names = check_pair(plan, out, run)
    if not artifacts_complete(out):
        raise ValueError('HTML·MD 3종 또는 문제설명 네 검토 미완료')
    verify_explanation(repo, out, names[1])
    evidence = read(run/'review.json')
    for kind in ('diagnosis', 'browser'):
        path = review_evidence(run, evidence.get(kind, {}))
        shutil.copy2(path, out/'.pack'/f'{kind}-evidence{path.suffix}')
    shutil.copy2(run/'review.json', out/'.pack/weakness-review.json')
    owned = names + [f'.assets/{Path(name).stem}.md' for name in names]
    hashes = {name: hashlib.sha256((out/name).read_bytes()).hexdigest() for name in owned}
    write(out/'.pack/weakness-run.json', dict(plan, status='complete', artifact_hashes=hashes))
    return dict(status='complete', output=str(out), files=names)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest='command', required=True)
    for name in ('select', 'prepare'):
        cmd = commands.add_parser(name)
        cmd.add_argument('--repo', type=Path, required=True)
        cmd.add_argument('--target')
        cmd.add_argument('--regenerate', action='store_true')
        if name == 'prepare': cmd.add_argument('--run', type=Path, required=True)
    study = commands.add_parser('study', help='해당 차시 HTML 3종의 학습 항목 목록; 읽기 완료 판정 아님')
    study.add_argument('--repo', type=Path, required=True)
    study.add_argument('--folder', required=True)
    for role in ('note', 'review', 'explanation'):
        study.add_argument('--'+role)
    for name in ('assemble', 'finish'):
        commands.add_parser(name).add_argument('--run', type=Path, required=True)
    args = parser.parse_args()
    try:
        if args.command == 'select': value = select(args.repo, args.target, args.regenerate)
        elif args.command == 'prepare': value = prepare(args.repo, args.target, args.run, args.regenerate)
        elif args.command == 'study': value = study_inventory(args.repo, args.folder, {role: getattr(args, role) for role in ('note', 'review', 'explanation') if getattr(args, role)})
        elif args.command == 'assemble': value = assemble(args.run)
        else: value = finish(args.run)
        print(json.dumps(value, ensure_ascii=False, indent=2))
    except (OSError, ValueError, KeyError, TypeError, subprocess.CalledProcessError) as exc:
        parser.exit(1, f'중단: {exc}\n')


if __name__ == '__main__': main()
